#
# This module holds the PDF report modules
#
# Design decisions:
# - Needs the optional `reportlab` package (`pip install fixturerig[pdf]`).
#   It is imported when the module is created, so a missing package is
#   reported as a configuration error before any test runs.
# - PdfReport is the full result report: summary table, then every group and
#   test with its verdict, specification and reported content. Complex
#   tables are rendered natively (reportlab table cells can hold flowables,
#   including nested tables); charts are drawn as vector graphics.
# - PdfTestSpecReport summarizes the test *specification* only: groups,
#   tests, descriptions (class docstrings), parameters and traceability. It
#   filters the stream down to lifecycle events and never shows a verdict,
#   so it can be generated by a dry review run as well as a real one.
#

from __future__ import annotations

import datetime
from pathlib import Path
from typing import Any
from xml.sax.saxutils import escape

from fixturerig.base.verdict import VerdictStatus
from fixturerig.report.elements import Chart, Element, Image, Table, Text, cell_text
from fixturerig.report.events import ContentEvent, VerdictEvent
from fixturerig.report.recording import GroupRecord, RecordingReport, RunRecord, TestRecord

_STATUS_COLORS = {
    VerdictStatus.PASSED: "#1f8a4c",
    VerdictStatus.FAILED: "#c62f2f",
    VerdictStatus.ERROR: "#9c1c1c",
    VerdictStatus.SKIPPED: "#b07800",
    VerdictStatus.NONE: "#8a3fa0",
    VerdictStatus.KNOWNFAILED: "#2a7f8f",
}
# Usable width of an A4 page with the margins used below, in points.
_FRAME_WIDTH = 480.0
_PALETTE = ["#2a6fdb", "#e0782b", "#2a9d5c", "#c03b5a", "#7b52c4", "#8a7a2a"]


def _require_reportlab() -> None:
    try:
        import reportlab  # noqa: F401
    except ImportError as exc:
        raise ImportError("PDF reports need the 'reportlab' package: pip install fixturerig[pdf]") from exc


class _PdfBase(RecordingReport):
    def __init__(self, path: Path, title: str = "", **kwargs):
        super().__init__(**kwargs)
        _require_reportlab()
        self.path = Path(path)
        self.title = title

    def write(self, run: RunRecord) -> None:
        from reportlab.lib.pagesizes import A4
        from reportlab.lib.units import mm
        from reportlab.platypus import SimpleDocTemplate

        self.path.parent.mkdir(parents=True, exist_ok=True)
        builder = _Builder()
        story = self.build(run, builder)
        document = SimpleDocTemplate(
            str(self.path),
            pagesize=A4,
            leftMargin=18 * mm,
            rightMargin=18 * mm,
            topMargin=18 * mm,
            bottomMargin=18 * mm,
            title=self.title or run.title,
        )
        document.build(story, onFirstPage=_footer, onLaterPages=_footer)

    def build(self, run: RunRecord, builder: "_Builder") -> list:
        raise NotImplementedError


class PdfReport(_PdfBase):
    """Writes a PDF result report.

    :param path: the file to write.
    :param title: the report heading; defaults to the run title.
    """

    def __init__(self, path: Path = Path("fixturerig-report.pdf"), **kwargs):
        super().__init__(path=path, **kwargs)

    def build(self, run: RunRecord, b: "_Builder") -> list:
        story = [b.heading(self.title or run.title, 0), b.meta(run)]
        rows = [["Test", "Verdict", "Duration", "Message"]]
        statuses = []
        for test in run.tests():
            status = test.status or VerdictStatus.NONE
            statuses.append(status)
            rows.append(
                [
                    " / ".join(test.started.path),
                    status.value,
                    f"{test.finished.duration:.3f}s" if test.finished else "-",
                    test.finished.verdict.message if test.finished else "test did not finish",
                ]
            )
        counts = ", ".join(f"{count} {status}" for status, count in run.counts().items()) or "no tests"
        story.append(b.paragraph(f"<b>Result:</b> {escape(counts)}"))
        if len(rows) > 1:
            story.append(b.text_table(rows, header=True, status_column=1, statuses=statuses))
        story.extend(self._children(run.root, b, depth=1))
        return story

    def _children(self, group: GroupRecord, b: "_Builder", depth: int) -> list:
        story: list = []
        for child in group.children:
            if isinstance(child, GroupRecord):
                story.append(b.heading(child.name or "(group)", min(depth, 3)))
                story.extend(self._children(child, b, depth + 1))
            elif isinstance(child, TestRecord):
                story.extend(self._render_test(child, b, min(depth, 3)))
            else:
                story.extend(b.content(child))
        return story

    def _render_test(self, test: TestRecord, b: "_Builder", level: int) -> list:
        spec = test.started
        status = test.status or VerdictStatus.NONE
        message = test.finished.verdict.message if test.finished else "test did not finish"
        color = _STATUS_COLORS[status]
        story = [
            b.heading(
                f'{escape(spec.name)} <font color="{color}">[{status.value.upper()}]</font>',
                level,
                markup=True,
            )
        ]
        story.extend(b.spec(spec, show_params=True))
        if message:
            story.append(b.paragraph(f'<font color="{color}">{escape(message)}</font>'))
        for event in test.content:
            story.extend(b.content(event))
        return story


class PdfTestSpecReport(_PdfBase):
    """Writes a PDF test specification: what is tested, how, and why. Ignores verdicts.

    :param path: the file to write.
    :param title: the document heading; defaults to "Test specification".
    """

    event_kinds = frozenset({"run_started", "run_finished", "group_started", "group_finished", "test_started"})

    def __init__(self, path: Path = Path("fixturerig-test-spec.pdf"), **kwargs):
        super().__init__(path=path, **kwargs)

    def build(self, run: RunRecord, b: "_Builder") -> list:
        tests = run.tests()
        story = [
            b.heading(self.title or "Test specification", 0),
            b.paragraph(f"{len(tests)} test(s), generated {datetime.date.today().isoformat()}"),
        ]
        rows = [["Test", "Class", "Traceability"]]
        rows += [[" / ".join(t.started.path), t.started.cls, ", ".join(t.started.traceability)] for t in tests]
        if len(rows) > 1:
            story.append(b.text_table(rows, header=True))
        story.extend(self._children(run.root, b, depth=1))
        return story

    def _children(self, group: GroupRecord, b: "_Builder", depth: int) -> list:
        story: list = []
        for child in group.children:
            if isinstance(child, GroupRecord):
                story.append(b.heading(child.name or "(group)", min(depth, 3)))
                story.extend(self._children(child, b, depth + 1))
            elif isinstance(child, TestRecord):
                story.append(b.heading(child.started.name, min(depth, 3)))
                story.extend(b.spec(child.started, show_params=True))
        return story


class _Builder:
    """Turns report elements into reportlab flowables."""

    def __init__(self):
        from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet

        sheet = getSampleStyleSheet()
        self.styles = {
            0: sheet["Title"],
            1: sheet["Heading1"],
            2: sheet["Heading2"],
            3: sheet["Heading3"],
        }
        self.body = sheet["BodyText"]
        self.small = ParagraphStyle("small", parent=self.body, fontSize=8, leading=10)
        self.mono = ParagraphStyle("mono", parent=sheet["Code"], fontSize=8, leading=10)
        self.muted = ParagraphStyle("muted", parent=self.body, textColor="#5d6874")

    def heading(self, text: str, level: int, markup: bool = False):
        from reportlab.platypus import Paragraph

        return Paragraph(text if markup else escape(text), self.styles[level])

    def paragraph(self, markup: str, style=None):
        from reportlab.platypus import Paragraph

        return Paragraph(markup, style or self.body)

    def text(self, text: str, style=None):
        return self.paragraph(escape(text).replace("\n", "<br/>"), style)

    def meta(self, run: RunRecord):
        started = (
            datetime.datetime.fromtimestamp(run.started.timestamp).strftime("%Y-%m-%d %H:%M:%S")
            if run.started
            else "-"
        )
        duration = f"{run.finished.duration:.2f}s" if run.finished else "aborted"
        return self.paragraph(f"Started {started} &middot; duration {duration}", self.muted)

    def spec(self, spec, show_params: bool) -> list:
        story = [self.paragraph(f"<b>Class:</b> {escape(spec.cls)}", self.small)]
        if spec.traceability:
            story.append(
                self.paragraph(f"<b>Traceability:</b> {escape(', '.join(spec.traceability))}", self.small)
            )
        if spec.description:
            story.append(self.text(spec.description))
        if show_params and spec.params:
            rows = [["Parameter", "Value"]] + [[name, repr(value)] for name, value in spec.params.items()]
            story.append(self.text_table(rows, header=True))
        return story

    def content(self, event: ContentEvent) -> list:
        if isinstance(event, VerdictEvent):
            status = event.verdict.status
            return [
                self.paragraph(
                    f'<font color="{_STATUS_COLORS[status]}"><b>{status.value}</b></font> '
                    f"{escape(event.verdict.message)}"
                )
            ]
        if event.element is None:
            return []
        flowable = self.element(event.element)
        return flowable if isinstance(flowable, list) else [flowable]

    def element(self, element: Element, width: float | None = None):
        """A flowable, or a list of flowables (valid both in the story and in table cells)."""
        if isinstance(element, Text):
            return self.text(element.text)
        if isinstance(element, Table):
            return self.table(element, width)
        if isinstance(element, Chart):
            return self.chart(element, width)
        if isinstance(element, Image):
            return self.image(element, width)
        return self.text(element.to_text())

    def text_table(self, rows: list[list[str]], header: bool, status_column: int | None = None, statuses=()):
        cells = [[self.text(cell_text(cell), self.small) for cell in row] for row in rows]
        if status_column is not None:
            for index, status in enumerate(statuses, start=1):
                cells[index][status_column] = self.paragraph(
                    f'<font color="{_STATUS_COLORS[status]}"><b>{escape(status.value)}</b></font>', self.small
                )
        return self._grid(cells, header)

    def table(self, table: Table, width: float | None = None):
        columns = table.column_count
        # Paragraphs in (nested) tables need fixed column widths to wrap.
        cell_width = (width or _FRAME_WIDTH) / max(columns, 1)
        rows: list[list[Any]] = []
        if table.headers:
            rows.append([self.text(h, self.small) for h in table.headers] + [""] * (columns - len(table.headers)))
        for row in table.rows:
            cells = [
                self.element(cell, width=cell_width - 8)
                if isinstance(cell, Element)
                else self.text(cell_text(cell), self.small)
                for cell in row
            ]
            rows.append(cells + [""] * (columns - len(cells)))
        if not rows:
            return self.text("(empty table)")
        grid = self._grid(rows, header=bool(table.headers), col_widths=[cell_width] * columns)
        if table.title:
            return [self.paragraph(f"<b>{escape(table.title)}</b>", self.small), grid]
        return grid

    def _grid(self, rows: list[list[Any]], header: bool, col_widths: list[float] | None = None):
        from reportlab.platypus import Table as RlTable
        from reportlab.platypus import TableStyle

        style = [
            ("GRID", (0, 0), (-1, -1), 0.4, "#d5dae0"),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
            ("LEFTPADDING", (0, 0), (-1, -1), 4),
            ("RIGHTPADDING", (0, 0), (-1, -1), 4),
        ]
        if header:
            style.append(("BACKGROUND", (0, 0), (-1, 0), "#eef1f4"))
        if col_widths is None:
            columns = max((len(row) for row in rows), default=1)
            col_widths = [_FRAME_WIDTH / columns] * columns
        grid = RlTable(rows, colWidths=col_widths, repeatRows=1 if header else 0, hAlign="LEFT")
        grid.setStyle(TableStyle(style))
        return grid

    def chart(self, chart: Chart, width: float | None = None):
        from reportlab.graphics.charts.barcharts import VerticalBarChart
        from reportlab.graphics.charts.legends import Legend
        from reportlab.graphics.charts.lineplots import LinePlot
        from reportlab.graphics.shapes import Drawing, String
        from reportlab.graphics.widgets.markers import makeMarker
        from reportlab.lib import colors

        total_w = min(width or 460, 460)
        if total_w < 120:
            return self.text(chart.to_text(), self.small)  # too narrow to draw
        total_h = total_w * 0.5
        drawing = Drawing(total_w, total_h + 30)
        drawing.add(String(0, total_h + 16, chart.title, fontName="Helvetica-Bold", fontSize=10))
        series = [s for s in chart.series if s.y]
        if not series:
            drawing.add(String(0, total_h / 2, "no data", fontSize=9))
            return drawing

        palette = [colors.HexColor(c) for c in _PALETTE]
        if chart.kind == "bar":
            categories: list = []
            for s in series:
                for x in s.x:
                    if x not in categories:
                        categories.append(x)
            plot = VerticalBarChart()
            plot.data = [
                [dict(zip(s.x, s.y)).get(category, 0) for category in categories] for s in series
            ]
            plot.categoryAxis.categoryNames = [str(c) for c in categories]
            # Bars must start at zero, or the smallest bar disappears.
            values = [value for row in plot.data for value in row]
            plot.valueAxis.valueMin = min(0, *values)
            plot.valueAxis.valueMax = max(0, *values) or 1
            for index in range(len(series)):
                plot.bars[index].fillColor = palette[index % len(palette)]
        else:
            plot = LinePlot()
            plot.data = [list(zip(map(float, s.x), map(float, s.y))) for s in series]
            for index in range(len(series)):
                line = plot.lines[index]
                line.strokeColor = palette[index % len(palette)]
                line.symbol = makeMarker("FilledCircle", size=3)
                if chart.kind == "scatter":
                    line.strokeColor = None
                    line.symbol.fillColor = palette[index % len(palette)]
            plot.xValueAxis.labels.fontSize = 7
            plot.yValueAxis.labels.fontSize = 7
        plot.x, plot.y = 40, 30
        plot.width, plot.height = total_w - 60, total_h - 40
        drawing.add(plot)

        if chart.x_label:
            drawing.add(String(40 + plot.width / 2, 4, chart.x_label, fontSize=8, textAnchor="middle"))
        if chart.y_label:
            drawing.add(String(0, total_h + 4, chart.y_label, fontSize=8))
        legend = Legend()
        legend.x, legend.y = total_w - 10, total_h + 22
        legend.alignment = "right"
        legend.columnMaximum = 1
        legend.fontSize = 8
        legend.dx = legend.dy = 6
        legend.colorNamePairs = [(palette[i % len(palette)], s.name) for i, s in enumerate(series)]
        legend.boxAnchor = "ne"
        drawing.add(legend)
        return drawing

    def image(self, image: Image, width: float | None = None):
        import io

        from reportlab.platypus import Image as RlImage

        from reportlab.lib.utils import ImageReader

        try:
            data = image.read_bytes()
            ImageReader(io.BytesIO(data)).getRGBData()  # decode now: a broken image must not break the PDF
            flowable = RlImage(io.BytesIO(data))
        except Exception as exc:  # unreadable file, broken data or unsupported format
            return self.text(f"{image.to_text()} could not be embedded: {exc}")
        max_w = width or 460
        if flowable.drawWidth > max_w:
            scale = max_w / flowable.drawWidth
            flowable.drawWidth *= scale
            flowable.drawHeight *= scale
        if image.caption:
            return [flowable, self.text(image.caption, self.small)]
        return flowable


def _footer(canvas, document) -> None:
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor("#5d6874")
    canvas.drawRightString(document.pagesize[0] - document.rightMargin, 10 * 2.83, f"Page {document.page}")
    canvas.drawString(document.leftMargin, 10 * 2.83, "FixtureRig")
    canvas.restoreState()
